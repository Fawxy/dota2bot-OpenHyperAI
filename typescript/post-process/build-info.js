// Writes bots/FunLib/humaniser/build_info.lua with the git commit being built ("+dirty" when the tree has changes),
// so every telemetry log names the build that produced it. Git-ignored: it changes on every commit.
const { execSync } = require("child_process");
const fs = require("fs");
const path = require("path");

function git(args) {
    return execSync(`git ${args}`, { cwd: path.join(__dirname, "../.."), encoding: "utf8" }).trim();
}

let build = "unknown";
try {
    build = git("rev-parse --short HEAD") + (git("status --porcelain --untracked-files=no") !== "" ? "+dirty" : "");
} catch (e) {
    console.error(`build-info: git failed, writing "unknown": ${e.message}`);
}
const out = path.join(__dirname, "../../bots/FunLib/humaniser/build_info.lua");
fs.writeFileSync(out, `-- Generated by typescript/post-process/build-info.js. Do not edit or commit.\nreturn { build = "${build}" }\n`);
console.log(`build-info: ${build}`);
